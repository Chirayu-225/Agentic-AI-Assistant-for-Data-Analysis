"""
test_clean_read.py — the Stage 0 reader, on files written HERE (not on benchmark data), so the
heuristics are not shaped by the dev split. Covers every case in the design review: trailing delimiter
vs ragged, footers before ragged, ragged extra / short fields, the ragged circuit breaker, padded titles,
thin-margin asks that show the candidate lines, headerless files, blank/duplicate headers, repeated
headers, two-level headers, quoted newlines (physical start lines), encodings, delimiters, identifier
hints, and "never crashes". Run: python test_clean_read.py
"""
import csv
import io
import os
import random
import sys

import clean_read as cr

FAIL = []
def check(label, cond, detail=""):
    print(f"[{'OK' if cond else 'FAIL'}] {label}" + (f" — {str(detail)[:300]}" if detail and not cond else ""))
    if not cond:
        FAIL.append(label)

def rd(text, enc="utf-8"):
    return cr.read(text.encode(enc) if isinstance(text, str) else text)

def kinds(r):
    return [a["kind"] for a in r["asks"]]

def excluded(r):
    return {x["line"]: x["reason"] for x in r["excluded"]}

TABLE = "id,name,amount,city\nA1,Neil,10.5,Pune\nA2,Priya,20,Delhi\nA3,Dev,30,Pune\nA4,Sam,5,Delhi\nA5,Tara,7.25,Pune\n"

# ── identity on a clean file ─────────────────────────────────────────────────
r = rd(TABLE)
check("clean file: status ok, header on line 1 and DECIDED", r["status"] == "ok" and r["structure"]["header"]["line"] == 1 and r["structure"]["header"]["decided"])
check("clean file: the table out equals the table in (raw strings, source lines)", r["rows"] == [(i + 2, row) for i, row in enumerate(list(csv.reader(io.StringIO(TABLE)))[1:])], r["rows"][:2])
check("clean file: zero flags, zero exclusions, zero asks, zero blanks", not (r["flags"] or r["excluded"] or r["asks"] or r["blanks"]))
check("clean file: every cell is a string", all(isinstance(c, str) for _, row in r["rows"] for c in row))
check("clean file: the structure report carries encoding and delimiter confidences", r["structure"]["encoding"]["confidence"] == 1.0 and r["structure"]["delimiter"]["confidence"] > 0.9)
check("clean file with CRLF line endings gives the same table", rd(TABLE.replace("\n", "\r\n"))["rows"] == r["rows"])

# ── encodings and delimiters ─────────────────────────────────────────────────
rb = rd(b"\xef\xbb\xbf" + TABLE.encode())
check("a UTF-8 BOM is stripped, reported, and does not reach the first column name", rb["structure"]["encoding"]["bom"] and rb["columns"][0]["name"] == "id")
rc = rd("id,name,city\nA1,Zo\u00eb,Z\u00fcrich\nA2,Ren\u00e9e,Lyon\nA3,Jos\u00e9,Rome\n", enc="cp1252")
check("a cp1252 export is decoded and the reader says it is less sure", rc["rows"][0][1][1] == "Zo\u00eb" and rc["structure"]["encoding"]["value"] == "cp1252" and rc["structure"]["encoding"]["confidence"] < 1.0, rc["structure"]["encoding"])
ru = rd(TABLE.encode("utf-16"))
check("a UTF-16 file is read", ru["status"] == "ok" and ru["structure"]["encoding"]["value"] == "utf-16" and len(ru["rows"]) == 5)
check("semicolon-delimited file", rd(TABLE.replace(",", ";"))["structure"]["delimiter"]["value"] == ";" and len(rd(TABLE.replace(",", ";"))["rows"]) == 5)
check("tab-delimited file", rd(TABLE.replace(",", "\t"))["structure"]["delimiter"]["value"] == "\t")
check("a single-column file needs no delimiter (nothing to sniff, no delimiter question)", "delimiter" not in kinds(rd("name\nNeil\nPriya\nDev\n")))
check("decimal commas inside quotes do not fool a semicolon sniff", rd('id;amount\nA1;"1,5"\nA2;"2,5"\nA3;"3,5"\n')["structure"]["delimiter"]["value"] == ";")

# ── headers: titles, padded titles, margins ──────────────────────────────────
plain = "Data export\nGenerated by ERP\n\n" + TABLE
r = rd(plain)
check("single-field title lines above the header: header found on line 4, decided", r["structure"]["header"]["line"] == 4 and r["structure"]["header"]["decided"] and not r["asks"])
check("... and the data rows keep their SOURCE lines", [ln for ln, _ in r["rows"]] == [5, 6, 7, 8, 9], [ln for ln, _ in r["rows"]])
check("... and the skipped blank line is reported", r["blanks"] == [3])
padded = "Quarterly report,,,\nExported by,ERP v4.2,,\n,,,\n" + TABLE
r = rd(padded)
check("titles PADDED with delimiters (same field count as the header) are not mistaken for the header",
      r["structure"]["header"]["line"] == 4 and r["structure"]["header"]["decided"] and not r["asks"], r["structure"]["header"])
check("... an empty padded row is a blank, not data", 3 in r["blanks"])
r = rd("Report,,,,,,,,\n" + TABLE)
check("a one-cell padded title directly above the header", r["structure"]["header"]["line"] == 2 and not r["asks"])
r = rd("id,name,amount,city\n" + TABLE.split("\n", 1)[1])
check("the header decision is not marginal on an ordinary file", r["structure"]["header"]["margin"] > 0.5, r["structure"]["header"])
r = rd("name,city\nAlice,Paris\nBob,Rome\nCara,Oslo\nDan,Lima\n")
check("an all-text table is genuinely ambiguous: the reader ASKS and shows the two candidate lines",
      kinds(r) == ["header"] and [c["line"] for c in r["asks"][0]["candidates"]] == [1, 2] and r["asks"][0]["candidates"][0]["text"] == "name,city", r["asks"])
check("... the user sees raw lines only (no values were guessed into the table)", len(r["rows"]) == 4)
r = rd("1,2.5,2024-01-03\n2,3.5,2024-01-04\n3,4.5,2024-01-05\n4,5.5,2024-01-06\n")
check("headerless file: asks, generates column names, and does NOT promote a data row to header",
      kinds(r) == ["headerless"] and [c["name"] for c in r["columns"]] == ["col_1", "col_2", "col_3"] and len(r["rows"]) == 4)
r = rd("id,,name,name,amount\nA1,x,Neil,N,10\nA2,y,Priya,P,20\nA3,z,Dev,D,30\nA4,w,Sam,S,5\n")
check("blank and duplicate header cells are named deterministically and flagged",
      [c["name"] for c in r["columns"]] == ["id", "unnamed_2", "name", "name_2", "amount"]
      and {f["reason"] for f in r["flags"]} >= {"blank_header_cell", "duplicate_header_cell"}, [c["name"] for c in r["columns"]])
r = rd("Unnamed: 0,name,amount\n0,Neil,10\n1,Priya,20\n2,Dev,30\n")
check("a pandas index column ('Unnamed: 0') is flagged", any(f["reason"] == "index_column_suspected" for f in r["flags"]))
r = rd("Region,,Sales,\n,Q1,Q2,Q3\nNorth,10,20,30\nSouth,11,21,31\nEast,12,22,32\n")
check("a two-level header is detected and asked about (out of scope), with both lines shown",
      kinds(r) == ["two_level_header_suspected"] and [c["line"] for c in r["asks"][0]["candidates"]] == [1, 2])
check("... while an ordinary sparse header is not mistaken for one", not rd("id,name,,amount\nA1,Neil,x,10.5\nA2,Priya,y,20\nA3,Dev,z,30\nA4,Sam,w,5\n")["asks"])

# ── trailing delimiter, totals, footers, repeated headers ────────────────────
r = rd(TABLE.replace("\n", ",\n"))
check("a trailing delimiter on every row is stripped, not treated as 'ragged'",
      r["structure"]["trailing_fields"] == 1 and len(r["columns"]) == 4 and not r["excluded"] and not r["flags"] and len(r["rows"]) == 5, (r["structure"]["trailing_fields"], r["excluded"]))
r = rd("id,name,note\nA1,Neil,\nA2,Priya,\nA3,Dev,hi\nA4,Sam,\nA5,Tara,\n")
check("a last column that is merely often EMPTY is not a phantom column (the header's last cell is filled)",
      r["structure"]["trailing_fields"] == 0 and len(r["columns"]) == 3 and len(r["rows"]) == 5 and not r["excluded"])
r = rd(TABLE + "TOTAL,,72.75,\nGenerated by ERP, 2024-03-01\nSource: export v4\n")
check("totals and footer notes are excluded with the right reason codes, and keep their lines",
      excluded(r) == {7: "total_row", 8: "footer_note", 9: "footer_note"}, excluded(r))
check("... footers were recognised BEFORE ragged handling: nothing was quarantined as a malformed row", "extra_field" not in excluded(r).values() and "possible_shift" not in excluded(r).values())
check("... and the raw line travels with the exclusion, for the review screen", [x["raw"] for x in r["excluded"]][1] == "Generated by ERP, 2024-03-01")
r = rd("id,name,amount\nA1,Neil,10\nid,name,amount\nA2,Priya,20\nA3,Dev,30\n")
check("a header repeated mid-file (concatenated exports) is excluded as repeated_header", excluded(r) == {3: "repeated_header"}, excluded(r))
check("a data row is never promoted to a header silently: the first row of a clean file stays data", len(rd(TABLE)["rows"]) == 5)

# ── ragged rows ──────────────────────────────────────────────────────────────
base = [f"A{i},Name{i},{i}.5,2024-01-{i:02d},Pune" for i in range(1, 41)]
H = "id,name,amount,day,city\n"
r = rd(H + "\n".join(base[:20] + ["A21,Name21,21.5,2024-01-21,Pune,extra stuff"] + base[20:]) + "\n")
x = r["excluded"]
check("an extra NON-empty field quarantines the row, and keeps the raw line", len(x) == 1 and x[0]["reason"] == "extra_field" and x[0]["raw"].endswith("extra stuff"), x)
check("... the unquoted-delimiter tag appears only when exactly one column is text-like", x[0]["tags"] == [] and "extra_field_unquoted_delimiter_suspected" in
      rd("id,note,amount\n" + "\n".join(f"{i},word{i},{i}.5" for i in range(1, 40)) + "\n40,Smith, John,40.5\n")["excluded"][0]["tags"])
r = rd(H + "\n".join(base[:20] + ["A21,Name21,21.5"] + base[20:]) + "\n")
check("a short row whose values still fit their columns is kept, flagged possible_shift, and padded",
      len(r["rows"]) == 41 and [f["reason"] for f in r["flags"]] == ["possible_shift"] and r["rows"][20][1][3:] == ["", ""], r["flags"])
r = rd(H + "\n".join(base[:20] + ["A21,21.5,2024-01-21,Pune"] + base[20:]) + "\n")
check("a short row with a MIDDLE field missing (values shifted into the wrong columns) is quarantined, not padded",
      excluded(r) == {22: "possible_shift"} and len(r["rows"]) == 40, (excluded(r), len(r["rows"])))
bad = base[:30] + [f"B{i},N,{i}.5,2024-02-01,Pune,extra" for i in range(10)]
r = rd(H + "\n".join(bad) + "\n")
check("circuit breaker: when >5% of rows are ragged it asks instead of quarantining a quarter of the file",
      kinds(r) == ["ragged_breaker"] and not [e for e in r["excluded"] if e["reason"] == "extra_field"] and len(r["rows"]) == 40, kinds(r))
check("... and shows the first ragged lines", len(r["asks"][0]["candidates"]) == 3 and r["asks"][0]["candidates"][0]["text"].startswith("B0"))

# ── physical coordinates ─────────────────────────────────────────────────────
q = 'id,note,n\nA1,"line one\nline two",1\nA2,plain,2\nA3,"x\ny\nz",3\nA4,end,4\n'
r = rd(q)
lines = q.split("\n")
check("a quoted field with newlines: each record's coordinate is the PHYSICAL line where it starts",
      [ln for ln, _ in r["rows"]] == [2, 4, 5, 8] and all(lines[ln - 1].startswith(row[0]) for ln, row in r["rows"]), [ln for ln, _ in r["rows"]])
f = "Title\n\nid,name\nA1,Neil\n\nA2,Priya\nA3,Dev\nA4,Sam\n"
r = rd(f)
check("blank lines in the middle keep every later row on its true source line", [ln for ln, _ in r["rows"]] == [4, 6, 7, 8] and r["blanks"] == [2, 5], ([ln for ln, _ in r["rows"]], r["blanks"]))

# ── identifier hints ─────────────────────────────────────────────────────────
ids = "bin,qty,zip\n" + "\n".join(f"{i:05d},{i},{(i * 7) % 100000:05d}" for i in range(1, 30)) + "\n"
r = rd(ids)
check("zero-padded digit columns are hinted as identifiers; plain integers are not", r["hints"]["identifier_columns"] == ["bin", "zip"], r["hints"])
check("the table itself still holds the raw text (hints are advice, not conversion)", r["rows"][0][1][0] == "00001")

# ── never crashes ────────────────────────────────────────────────────────────
for label, blob in (("empty", b""), ("whitespace only", b" \n\t\n"), ("only a header", b"a,b,c\n"), ("a single line", b"hello"),
                    ("NUL bytes", b"a,b\n1,\x002\n3,4\n"), ("lone quote", b'a,b\n1,"2\n3,4\n'), ("huge field", b"a,b\n1," + b"x" * 400000 + b"\n")):
    r = cr.read(blob)
    check(f"never crashes: {label} -> a structured result", r["status"] in ("ok", "unreadable") and isinstance(r["reason"], str) and "lines_parsed" in r, r["reason"])
check("an unreadable file says why", cr.read(b"")["status"] == "unreadable" and cr.read(b"")["reason"])
rng = random.Random(7)
crashed = []
for i in range(300):
    kind = i % 3
    blob = (bytes(rng.randrange(256) for _ in range(rng.randrange(1, 400))) if kind == 0 else
            "\n".join(",".join(rng.choice(["a", "1", "", '"q', "2024-01-01", ";", "\t"]) for _ in range(rng.randrange(1, 9))) for _ in range(rng.randrange(1, 30))).encode()
            if kind == 1 else (TABLE.encode()[: rng.randrange(1, len(TABLE))]))
    try:
        r = cr.read(blob)
        assert r["status"] in ("ok", "unreadable")
    except Exception as e:
        crashed.append((i, repr(e)))
check("fuzz: 300 random / truncated / garbled inputs never raise", not crashed, crashed[:3])

# ── on dev control files only (clean data, never frozen) ─────────────────────
import clean_score as cs
cases = cs.load_cases("mini", "dev")
ctrl = [c for c in cases if c.control]
for c in ctrl:
    r = cr.read(c.data)
    truth = [(ln, row) for ln, row in csv.reader(io.StringIO(c.data.decode("utf-8-sig"))) and []]
    recs = []
    rd_ = csv.reader(io.StringIO(c.data.decode("utf-8-sig")))
    for row in rd_:
        recs.append((rd_.line_num, row))
    check(f"{c.id}: the reader is the identity on a clean control (same rows, zero flags/exclusions/asks)",
          r["rows"] == recs[1:] and not (r["flags"] or r["excluded"] or r["asks"] or r["blanks"]), (len(r["rows"]), len(recs) - 1, r["asks"]))

# ── the Stage 0 pipeline (needs pandas) ──────────────────────────────────────
try:
    import pandas  # noqa: F401
    have = True
except ImportError:
    have = False
    print("[SKIP] Stage 0 pipeline checks: pandas is not installed here")
if have:
    import clean_adapter_stage0 as a0
    body = "\n".join(f"{i:05d},A{i},{i}.5" for i in range(1, 12))
    d = a0.run("t", ("Title line\n\nbin,name,amount\n" + body + "\n\nTOTAL,,60\nGenerated by ERP\n").encode(), {})
    P = d["predictions"]
    act = lambda ln: sorted(p["action"] for p in P if p["line"] == ln and p["col_index"] is None)
    check("pipeline: runs, header on line 3", d["status"] == "ok" and d["structure"]["header_line"] == 3 and d["structure"]["columns"] == ["bin", "name", "amount"], d.get("error"))
    check("pipeline: a zero-padded identifier column is NOT turned into a number (no fix on it)", not [p for p in P if p["col_index"] == 1 and p["action"] in ("fix", "blank")], [p for p in P if p["col_index"] == 1][:2])
    check("pipeline: blank lines, the TOTAL row and the footer are reported at their source lines",
          act(2) == ["ignore"] and act(15) == ["ignore"] and act(16) == ["quarantine"] and act(17) == ["quarantine"], (act(2), act(15), act(16), act(17)))
    check("pipeline: the gate says it decided", d["gate"]["asked"] is False)
    d2 = a0.run("t2", b"", {})
    check("pipeline: an unreadable file is a failed case with a reason, not an exception", d2["status"] == "error" and "unreadable" in d2["error"])
    d3 = a0.run("t3", b"name,city\nAlice,Paris\nBob,Rome\nCara,Oslo\nDan,Lima\n", {})
    check("pipeline: an ambiguous header is reported as ASKED, with the candidate lines", d3["gate"]["asked"] and d3["gate"]["asks"][0]["candidates"][0]["text"] == "name,city")

print()
if FAIL:
    print(f"{len(FAIL)} check(s) failed: {FAIL}")
    sys.exit(1)
print("all checks passed")
