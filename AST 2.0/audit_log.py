"""
audit_log.py — append-only, tamper-evident audit trail of security-relevant
events: who called what, what the sandbox blocked, what PII was redacted,
which injection phrasings were seen, who got rate-limited.

WHY THIS EXISTS
    The app already DEFENDS (sandbox, PII redaction, injection fencing),
    but until now left almost no durable trace of those defenses
    firing — a few print() lines that vanish with the process. A defense
    nobody can inspect afterwards can't be investigated, tuned, or shown
    to a reviewer. This module is that trace.

WHAT IS LOGGED, AND WHAT IS NOT
    Logged: event type, timestamp, request id, session id, endpoint,
    status, durations, counts (e.g. "2x EMAIL redacted"), SHA-256 hashes
    of code / URLs, and — only for sandbox BLOCKS — the first 200
    characters of the rejected code (it's attack evidence and is
    generated by the LLM, not copied from the user's data).
    NEVER logged: request bodies, prompts, dataset values, redacted PII
    values, file contents, the shared secret. File URLs are stored as
    short hashes (Blob URLs are semi-secret). Client IPs are stored as
    short hashes. Set AUDIT_LOG_CODE=1 to also store the executed code
    (truncated) — off by default because generated code can quote data.

FORMAT
    One JSON object per line (JSONL), written through a rotating file
    handler (10 MB x 5 files). If the log directory isn't writable
    (read-only filesystems on some hosts), events go to stdout instead,
    which hosts like Render capture.

TAMPER EVIDENCE
    Each record carries `seq`, `prev` and `hash` where
    hash = SHA-256(prev + canonical-JSON-of-the-record-without-hash).
    Editing, deleting or reordering a line breaks every later link, and
    verify_chain() reports the first bad line. A new process starts a new
    chain segment (prev = "GENESIS"), so restarts and log rotation don't
    produce false alarms. This detects accidental or casual tampering.
    An attacker with write access to the log AND the ability to recompute
    every later hash could still rewrite history — ship the log to
    external storage (or anchor the latest hash somewhere) if that
    threat matters.

CONFIG (environment variables)
    AUDIT_LOG_PATH   default logs/audit.jsonl
    AUDIT_LOG_CODE   "1" to include truncated executed code
    AUDIT_LOG_STDOUT "1" to ALSO echo every record to stdout
    AUDIT_LOG_DISABLED "1" to turn the whole thing off (tests)
"""

from __future__ import annotations

import contextvars
import hashlib
import json
import logging
import logging.handlers
import os
import threading
import time
import uuid
from typing import Any, Optional

GENESIS = "GENESIS"

_lock = threading.Lock()
_logger: Optional[logging.Logger] = None
_logger_path: Optional[str] = None
_prev_hash = GENESIS
_seq = 0
_warned = False

# Per-request context, shared by every record written while handling it.
# A plain dict stored in the contextvar so code running in a worker
# thread can add fields that the middleware later reads back.
_request_ctx: contextvars.ContextVar[Optional[dict]] = contextvars.ContextVar("audit_ctx", default=None)


# ─────────────────────────────────────────────────────────────────────────────
# helpers
# ─────────────────────────────────────────────────────────────────────────────

def sha_short(value: Any, n: int = 12) -> str:
    return hashlib.sha256(str(value).encode("utf-8", "replace")).hexdigest()[:n]


def log_path() -> str:
    return os.environ.get("AUDIT_LOG_PATH", os.path.join("logs", "audit.jsonl"))


def _disabled() -> bool:
    return os.environ.get("AUDIT_LOG_DISABLED") == "1"


def _canonical(record: dict) -> str:
    return json.dumps(record, sort_keys=True, separators=(",", ":"), default=str)


def _compute_hash(prev: str, record_without_hash: dict) -> str:
    return hashlib.sha256((prev + _canonical(record_without_hash)).encode("utf-8")).hexdigest()


def _get_logger() -> logging.Logger:
    """Creates the logger lazily and re-creates it if AUDIT_LOG_PATH
    changed (tests point it at a temp file)."""
    global _logger, _logger_path
    path = log_path()
    if _logger is not None and _logger_path == path:
        return _logger

    logger = logging.getLogger(f"audit.{path}")
    logger.setLevel(logging.INFO)
    logger.propagate = False
    for h in list(logger.handlers):
        logger.removeHandler(h)
        try:
            h.close()
        except Exception:
            pass

    handler: logging.Handler
    try:
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        handler = logging.handlers.RotatingFileHandler(
            path, maxBytes=10 * 1024 * 1024, backupCount=5, encoding="utf-8"
        )
    except OSError as e:
        print(f"[audit_log] cannot write {path!r} ({e}); falling back to stdout", flush=True)
        handler = logging.StreamHandler()
    handler.setFormatter(logging.Formatter("%(message)s"))
    logger.addHandler(handler)
    if os.environ.get("AUDIT_LOG_STDOUT") == "1" and not isinstance(handler, logging.StreamHandler):
        logger.addHandler(logging.StreamHandler())

    _logger, _logger_path = logger, path
    return logger


def reset_for_tests() -> None:
    """Closes handlers and restarts the chain. Tests only."""
    global _logger, _logger_path, _prev_hash, _seq
    with _lock:
        if _logger is not None:
            for h in list(_logger.handlers):
                try:
                    h.close()
                except Exception:
                    pass
                _logger.removeHandler(h)
        _logger = _logger_path = None
        _prev_hash = GENESIS
        _seq = 0


# ─────────────────────────────────────────────────────────────────────────────
# request context
# ─────────────────────────────────────────────────────────────────────────────

def begin_request(**fields) -> tuple[dict, contextvars.Token]:
    ctx = {"request_id": uuid.uuid4().hex[:12], **fields}
    token = _request_ctx.set(ctx)
    return ctx, token


def end_request(token: contextvars.Token) -> None:
    _request_ctx.reset(token)


def bind(**fields) -> None:
    """Attach fields (e.g. session_id) to the current request's context so
    every later record in this request carries them."""
    ctx = _request_ctx.get()
    if ctx is not None:
        ctx.update({k: v for k, v in fields.items() if v is not None})


def current_context() -> dict:
    return _request_ctx.get() or {}


# ─────────────────────────────────────────────────────────────────────────────
# writing
# ─────────────────────────────────────────────────────────────────────────────

def record(event: str, **fields) -> Optional[dict]:
    """Writes one audit record. Never raises: a broken audit trail must
    not take the app down, but it warns once on stdout so it isn't
    silently broken either."""
    global _prev_hash, _seq, _warned
    if _disabled():
        return None
    try:
        with _lock:
            rec = {
                "ts": round(time.time(), 3),
                "event": event,
                **{k: v for k, v in current_context().items()},
                **fields,
            }
            _seq += 1
            rec["seq"] = _seq
            rec["prev"] = _prev_hash
            rec["hash"] = _compute_hash(_prev_hash, rec)
            _get_logger().info(_canonical(rec))
            _prev_hash = rec["hash"]
            return rec
    except Exception as e:  # pragma: no cover - defensive
        if not _warned:
            _warned = True
            print(f"[audit_log] WARNING: audit write failed ({type(e).__name__}: {e}); "
                  f"audit trail is incomplete", flush=True)
        return None


def record_sandbox(kind: str, code: str, success: bool, error: str, elapsed_ms: float) -> None:
    """One sandbox run. `kind` is pandas / sql / large_csv / multi_table.
    Distinguishes a SECURITY BLOCK (code rejected before running, or a
    proxy refusal) from an ordinary runtime error and from a timeout."""
    err = error or ""
    low = err.lower()
    blocked = err.startswith("Security block")
    # The sandbox's own messages: "Query exceeded the Ns execution limit and
    # was stopped" (wall clock) and "Memory limit exceeded" / "...memory limit
    # was hit during allocation" (RLIMIT_AS). Memory is checked first because
    # its message also contains "exceeded".
    out_of_memory = "memory limit" in low
    timed_out = (not out_of_memory) and ("execution limit" in low or "timed out" in low or "timeout" in low)
    fields: dict[str, Any] = {
        "kind": kind,
        "success": bool(success),
        "elapsed_ms": round(elapsed_ms, 1),
        "code_sha256": sha_short(code, 16),
        "code_len": len(code or ""),
    }
    if not success:
        fields["outcome"] = ("blocked" if blocked else "memory" if out_of_memory
                             else "timeout" if timed_out else "error")
        fields["error"] = err[:300]
    else:
        fields["outcome"] = "ok"
    if blocked:
        fields["code_preview"] = (code or "")[:200]
    elif os.environ.get("AUDIT_LOG_CODE") == "1":
        fields["code"] = (code or "")[:2000]
    record("sandbox_blocked" if blocked else "sandbox_run", **fields)


# ─────────────────────────────────────────────────────────────────────────────
# reading / verifying
# ─────────────────────────────────────────────────────────────────────────────

def verify_chain(path: Optional[str] = None) -> dict:
    """Walks the log and re-computes every hash.
    Returns {ok, records, segments, first_bad_line, reason}. A record with
    prev == GENESIS starts a new segment (process restart); the first line
    of a rotated file may start mid-chain and is accepted as a segment start."""
    path = path or log_path()
    if not os.path.exists(path):
        return {"ok": True, "records": 0, "segments": 0, "first_bad_line": None, "reason": "no log file yet"}
    prev: Optional[str] = None
    records = segments = 0
    with open(path, "r", encoding="utf-8") as f:
        for lineno, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                return {"ok": False, "records": records, "segments": segments,
                        "first_bad_line": lineno, "reason": "line is not valid JSON"}
            claimed = rec.pop("hash", None)
            if claimed is None or "prev" not in rec:
                return {"ok": False, "records": records, "segments": segments,
                        "first_bad_line": lineno, "reason": "record is missing hash/prev"}
            if prev is None or rec["prev"] == GENESIS:
                segments += 1
            elif rec["prev"] != prev:
                return {"ok": False, "records": records, "segments": segments,
                        "first_bad_line": lineno, "reason": "chain broken: a record was removed, reordered or inserted"}
            if _compute_hash(rec["prev"], rec) != claimed:
                return {"ok": False, "records": records, "segments": segments,
                        "first_bad_line": lineno, "reason": "record content was modified"}
            prev = claimed
            records += 1
    return {"ok": True, "records": records, "segments": segments, "first_bad_line": None, "reason": "chain intact"}


def summarize(path: Optional[str] = None, max_lines: int = 50000) -> dict:
    """Counts events by type over the most recent `max_lines` records.
    Used by the admin stats endpoint."""
    path = path or log_path()
    counts: dict[str, int] = {}
    if not os.path.exists(path):
        return counts
    with open(path, "r", encoding="utf-8") as f:
        lines = f.readlines()[-max_lines:]
    for line in lines:
        try:
            ev = json.loads(line).get("event", "?")
        except json.JSONDecodeError:
            ev = "corrupt"
        counts[ev] = counts.get(ev, 0) + 1
    return counts
