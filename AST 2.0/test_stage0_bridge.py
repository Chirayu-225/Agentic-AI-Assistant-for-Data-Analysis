"""
test_stage0_bridge.py — the structure-only bridge (stage0_bridge.py) and its wiring into the app's read path.

What must hold: a clean file is returned untouched (None); structure defects are repaired and reported; anything unsure,
too big, switched off or crashing leaves the file alone; the legacy read path never calls the bridge.
Run: python test_stage0_bridge.py
"""
import glob
import io
import os

import pandas as pd

FAIL = []


def check(label, cond, detail=""):
    print(f"[{'OK' if cond else 'FAIL'}] {label}" + (f" — {detail}" if detail and not cond else ""))
    if not cond:
        FAIL.append(label)


def table(n=60, junk=0, footer=(), total=False, extra=()):
    lines = [f"Quarterly export line {i}" for i in range(junk)]
    lines.append("id,name,amount")
    for i in range(1, n + 1):
        lines.append(f"{i},Name{i % 7},{10 + i}.5")
    for i in extra:                                  # a row with one extra trailing field, at position i
        lines[(junk + 1) + i] = lines[(junk + 1) + i] + ",extra"
    if total:
        lines.append(f"Total,,{sum(10 + i + .5 for i in range(1, n + 1))}")
    lines.extend(footer)
    return ("\n".join(lines) + "\n").encode("utf-8")


def main():
    import cleaning
    import file_reader
    import stage0_bridge as sb

    # 1. a file with no structural defect is returned untouched
    clean = table()
    new, notes, info = sb.repair(clean)
    check("clean file: nothing to repair (None, no notes)", new is None and notes == [] and info["reason"] == "no structural defect")
    check("clean file: bridge_bytes returns the original bytes", sb.bridge_bytes(clean) is clean)

    here = os.path.dirname(os.path.abspath(__file__))
    files = [f for f in glob.glob(os.path.join(here, "eval_data", "**", "*.csv"), recursive=True)
             if os.sep + "clean_bench" + os.sep not in f and os.sep + "exp" + os.sep not in f]
    check("there are real CSVs to test identity on", len(files) >= 8, str(len(files)))
    repaired = {os.path.basename(f): sb.repair(open(f, "rb").read()) for f in files}
    changed = sorted(n for n, (new_bytes, _n, _i) in repaired.items() if new_bytes is not None)
    # invoices_messy.csv really ends with a TOTAL row; counting it as an invoice would inflate every sum and count.
    check("only the one file that really has a TOTAL row is repaired; every other CSV is untouched",
          changed == ["invoices_messy.csv"], str(changed))
    check("... and the reason is exactly that total row",
          repaired["invoices_messy.csv"][2].get("set_aside") == {"total_row": 1} and repaired["invoices_messy.csv"][2].get("header_line") == 1,
          str(repaired["invoices_messy.csv"][2]))

    # 2. junk lines above the header
    junk = table(junk=3)
    new, notes, info = sb.repair(junk)
    check("header offset: repaired", new is not None and info["changed"] and info["header_line"] == 4)
    df = pd.read_csv(io.BytesIO(new))
    check("header offset: the real header and all rows survive", list(df.columns) == ["id", "name", "amount"] and len(df) == 60)
    check("header offset: reported in plain English", any("Skipped 3 lines above the header" in n for n in notes), str(notes))

    # 3. footer notes and a total row are set aside, not counted
    new, notes, info = sb.repair(table(footer=("Report generated by finance", "Confidential", "End of file")))
    df = pd.read_csv(io.BytesIO(new)) if new else None
    check("footer notes: removed, all 60 data rows kept", df is not None and len(df) == 60, str(None if df is None else len(df)))
    check("footer notes: reported", any("footer note line" in n for n in notes), str(notes))
    new, notes, info = sb.repair(table(total=True))
    df = pd.read_csv(io.BytesIO(new)) if new else None
    check("total row: removed, all 60 data rows kept", df is not None and len(df) == 60 and "Total" not in set(df["id"].astype(str)),
          str(None if df is None else len(df)))
    check("total row: reported", any("total row" in n for n in notes), str(notes))

    # 4. a row with one extra trailing field is kept only when its shape fits
    new, notes, info = sb.repair(table(extra=(10, 20)))
    df = pd.read_csv(io.BytesIO(new)) if new else None
    check("extra trailing field: the two rows are kept (extra value dropped)", df is not None and len(df) == 60 and info["restored"] == 2,
          f"{None if df is None else len(df)} {info}")
    check("extra trailing field: reported", any("extra trailing value" in n for n in notes), str(notes))
    shifted = table().decode().splitlines()
    shifted[11] = "11,Smith, John,31.5"            # an unquoted comma inside a text value: the row is SHIFTED, not just long
    new, notes, info = sb.repair(("\n".join(shifted) + "\n").encode())
    df = pd.read_csv(io.BytesIO(new)) if new else None
    check("shifted row: NOT restored, and the report says it was left out",
          new is not None and info["left_out"] == 1 and info["restored"] == 0 and any("Left out 1 row" in n for n in notes), f"{info}")
    check("shifted row: the other rows are intact", df is not None and len(df) == 59)

    # 5. guards: size, switch, crash, unsure reader
    os.environ["STAGE0_BRIDGE_MAX_BYTES"] = "10"
    check("larger than the limit: left alone", sb.repair(junk)[0] is None and "larger" in sb.repair(junk)[2]["reason"])
    del os.environ["STAGE0_BRIDGE_MAX_BYTES"]
    os.environ["AST_STAGE0_BRIDGE"] = "0"
    check("switched off: left alone", sb.repair(junk)[0] is None and sb.repair(junk)[2]["reason"] == "switched off")
    del os.environ["AST_STAGE0_BRIDGE"]
    import clean_read
    real = clean_read.read
    clean_read.read = lambda data: (_ for _ in ()).throw(RuntimeError("boom"))
    check("the reader crashes: left alone, nothing raised", sb.repair(junk)[0] is None)
    clean_read.read = lambda data: {"status": "ok", "asks": [{"kind": "header"}], "structure": {}, "columns": [], "rows": [], "excluded": []}
    check("the reader has an open question: left alone", sb.repair(junk)[0] is None and "not sure" in sb.repair(junk)[2]["reason"])
    clean_read.read = real
    check("garbage bytes: left alone, nothing raised", sb.repair(b"\x00\x01\x02\xff\xfe")[0] is None)

    # 6. the app path repairs; the legacy path never does
    f_safe = file_reader._read_tabular_file_uncached(junk, "x.csv", na_policy="safe")
    check("safe read: the table is correct", list(f_safe.columns) == ["id", "name", "amount"] and len(f_safe) == 60)
    check("safe read: structure notes are attached", any("above the header" in n for n in f_safe.attrs.get("reader_notes", [])))
    try:                                         # the legacy reader either raises on the junk lines or misreads the header
        f_legacy = file_reader._read_tabular_file_uncached(junk, "x.csv")
        legacy_still_broken = list(f_legacy.columns) != ["id", "name", "amount"]
    except Exception:
        legacy_still_broken = True
    check("legacy read: unchanged (the junk lines still break it, so the bridge is not used)", legacy_still_broken)
    _, log = cleaning.rule_based_clean(f_safe, na_policy="safe")
    check("cleaning report: the structure repair is listed", any("above the header" in str(l) for l in log), str(log[:3]))
    f_clean = file_reader._read_tabular_file_uncached(clean, "x.csv", na_policy="safe")
    check("safe read of a clean file: no structure notes", "reader_notes" not in f_clean.attrs)

    print()
    if FAIL:
        print(f"FAILED: {FAIL}")
        raise SystemExit(1)
    print("DONE — all checks passed.")


if __name__ == "__main__":
    main()
