"""
clean_read.py — Stage 0: read a delimited file into a table of RAW STRINGS with source coordinates,
and report what it found about the file's structure. It never crashes and never types anything.

    python clean_read.py FILE        # prints the structure report (a quick smoke test on a real export)

WHAT IT RETURNS (a plain dict; see read())
    status      "ok" | "unreadable" (with a reason and how many lines were parsed)
    structure   encoding / delimiter (each with a confidence), header line, columns, trailing phantom fields
    rows        [(line, fields)] — every cell a string; `line` is the PHYSICAL line where the record starts
    excluded    rows kept OUT of the table, each with a reason code and the raw line
                (footer_note, total_row, extra_field, possible_shift, repeated_header)
    flags       rows kept IN but doubtful (possible_shift) — not pre-selected for analysis
    blanks      blank lines the reader skipped
    asks        the structure-confirm gate: questions the reader will NOT guess at, each carrying the
                raw candidate lines so the user (never an LLM) can answer them
    hints       column hints for a later typing step (identifier columns that must stay text)

ORDER OF OPERATIONS (it matters)
    decode -> sniff delimiter -> parse records (physical start lines) -> choose header -> strip a
    trailing delimiter -> totals and footers -> repeated headers -> ragged rows -> circuit breaker.
    Footers and totals run BEFORE ragged handling, or "Generated by X" is quarantined as malformed.

HEADER CHOICE scores each of the first lines on five signals (weights below are fixed up front):
    fill ratio (a title has one or two cells, a header has nearly all), uniqueness, stable width of the
    rows below, type contrast with the rows below (labels over numbers/dates, and not repeated below),
    and earliness among dense rows. Titles padded with delimiters ("Quarterly report,,,,,") have the same
    field count as the header, which is why width alone is not used. When the top two candidates are close
    the reader ASKS and shows both lines.

Not solved here, only detected and asked: two-level headers, headerless files, a delimiter or encoding
that is a close call. Two readers is debt: this one replaces file_reader's CSV path once its dev targets
(stage0_targets.py) are met and Stage 1 consumes its output; the old CSV path is then deleted, not kept.
"""

from __future__ import annotations

import csv
import io
import re
import sys
from collections import Counter

# ── constants, fixed before the first scorer run ─────────────────────────────
SAMPLE_LINES = 15
BELOW_ROWS = 25
W_FILL, W_UNIQ, W_STABLE, W_CONTRAST, W_EARLY = 0.30, 0.15, 0.20, 0.25, 0.10
DENSE_FILL = 0.5            # a line with at least this share of cells filled is a candidate table row
PLAUSIBLE_LABELNESS = 0.6   # share of non-empty cells that must be label-like to be a candidate header
HEADER_MIN_SCORE = 0.60
HEADER_MIN_MARGIN = 0.10
FOOTER_FILL = 0.30          # below this a line at the end is a footer, not a record
FOOTER_MAX_SHARE = 0.20     # ...but never more than this share of the file (or FOOTER_MIN_LINES, for tiny files)
FOOTER_MIN_LINES = 5
RAGGED_BREAKER = 0.05       # more ragged rows than this and the delimiter/quoting is suspect, not the rows
TRAILING_MAX = 3
TRAILING_AGREEMENT = 0.70
ID_SHARE = 0.90
DELIMS = [",", ";", "\t", "|"]

_TOTAL = re.compile(r"^(grand\s+)?(total|subtotal|sum)s?\s*:?$", re.I)
_DATE = re.compile(r"^(\d{4}[-/.]\d{1,2}[-/.]\d{1,2}|\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}|\d{1,2}[ -][A-Za-z]{3,9}[ -,]*\d{2,4}"
                   r"|[A-Za-z]{3,9}\.? \d{1,2},? \d{2,4}|\d{8})(?:[ T]\d{1,2}:\d{2}(?::\d{2})?)?$")
_NUM = re.compile(r"^[\(\-+]?\s*(?:[$£€₹¥]|[A-Za-z]{2,3}\.?)?\s*\d[\d,.' \u00a0]*(?:\s*(?:[$£€₹¥%]|[A-Za-z]{3}))?\)?$")
_UNNAMED = re.compile(r"^unnamed:?\s*\d+$", re.I)


def _cls(s: str):
    t = s.strip()
    if not t:
        return None
    if _DATE.match(t):
        return "date"
    if _NUM.match(t):
        return "number"
    return "text"


def _label_like(s: str) -> bool:
    """A header-style cell: text with no digits. Identifiers ("A1", "ORD-000041") are data, not labels."""
    t = s.strip()
    return bool(t) and _cls(t) == "text" and not any(ch.isdigit() for ch in t)


def _filled(row) -> int:
    return sum(1 for c in row if c.strip())


# ── decoding and delimiter ───────────────────────────────────────────────────
def _decode(data: bytes):
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        try:
            return data.decode("utf-16"), {"value": "utf-16", "bom": True, "confidence": 0.95}
        except UnicodeDecodeError:
            pass
    bom = data.startswith(b"\xef\xbb\xbf")
    try:
        return data.decode("utf-8-sig"), {"value": "utf-8", "bom": bom, "confidence": 1.0 if data.isascii() else 0.99}
    except UnicodeDecodeError:
        pass
    try:
        return data.decode("cp1252"), {"value": "cp1252", "bom": False, "confidence": 0.7}
    except UnicodeDecodeError:
        return data.decode("latin-1"), {"value": "latin-1", "bom": False, "confidence": 0.4}


def _sniff(text: str):
    lines = [l for l in text.split("\n") if l.strip()][:60]
    scored = []
    for d in DELIMS:
        widths = []
        for l in lines:
            try:
                widths.append(len(next(csv.reader([l], delimiter=d))))
            except Exception:
                widths.append(1)
        (m, cnt), = Counter(widths).most_common(1)
        scored.append((cnt / len(widths) if m >= 2 else 0.0, m, d))
    scored.sort(reverse=True)
    best, second = scored[0], scored[1]
    if best[0] == 0.0:
        return ",", 1.0, False  # a single column: nothing to sniff
    close = second[0] > 0 and best[0] - second[0] < 0.10 and second[2] != best[2]
    return best[2], best[0], (best[0] < 0.6 or close)


def _parse(text: str, delim: str):
    """[(start_line, fields)] with the PHYSICAL line where each record starts (a quoted field may span lines)."""
    recs, prev, err = [], 0, ""
    rd = csv.reader(io.StringIO(text), delimiter=delim)
    try:
        for row in rd:
            end = rd.line_num
            recs.append((prev + 1, row))
            prev = end
    except csv.Error as e:
        err = str(e)
    return recs, err


# ── header scoring ───────────────────────────────────────────────────────────
def _score(row, below, wmode: int, dense_before: int) -> dict:
    same = [c.strip() for c in row]
    below = [b for b in below if [c.strip() for c in b] != same]  # a repeated header is noise, not data
    ne = [c.strip() for c in row if c.strip()]
    fill = min(1.0, len(ne) / max(wmode, 1))
    uniq = len({x.lower() for x in ne}) / len(ne) if ne else 0.0
    labelness = sum(1 for x in ne if _label_like(x)) / len(ne) if ne else 0.0
    stable = sum(1 for b in below if len(b) == len(row)) / len(below) if below else 0.5
    parts = []
    for j, c in enumerate(row):
        if not _label_like(c):
            continue
        col = [b[j].strip() for b in below if j < len(b) and b[j].strip()]
        if col:
            top, n = Counter(_cls(v) for v in col).most_common(1)[0]
            type_part = 1.0 if top in ("number", "date") and n / len(col) >= 0.8 else 0.5
            novelty = 0.0 if c.strip().lower() in {v.lower() for v in col} else 1.0
            parts.append(0.5 * type_part + 0.5 * novelty)
        else:
            parts.append(0.5)
    contrast = sum(parts) / len(parts) if parts else 0.0
    early = 1.0 / (1 + dense_before) if fill >= DENSE_FILL else 0.0
    score = (W_FILL * fill + W_UNIQ * uniq + W_STABLE * stable + W_CONTRAST * (0.5 * labelness + 0.5 * contrast) + W_EARLY * early)
    return {"fill": fill, "uniq": uniq, "stable": stable, "labelness": labelness, "contrast": contrast, "early": early, "score": score}


# ── the reader ───────────────────────────────────────────────────────────────
def read(data: bytes) -> dict:
    res = {"status": "ok", "reason": "", "lines_parsed": 0, "structure": {}, "columns": [], "rows": [], "excluded": [],
           "flags": [], "blanks": [], "asks": [], "hints": {"identifier_columns": []}}
    try:
        _read(data, res)
    except Exception as e:  # noqa: BLE001 — the reader never crashes; a failure is a result
        res["status"], res["reason"] = "unreadable", f"internal error: {type(e).__name__}: {e}"
    return res


def _fail(res, reason):
    res["status"], res["reason"] = "unreadable", reason
    return res


def _read(data: bytes, res: dict) -> None:
    if not data or not data.strip():
        _fail(res, "the file is empty")
        return
    text, enc = _decode(data)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    raw_lines = text.split("\n")
    raw = lambda ln: raw_lines[ln - 1] if 0 < ln <= len(raw_lines) else ""
    st = res["structure"]
    st["encoding"] = enc
    if enc["confidence"] < 0.5:
        res["asks"].append({"kind": "encoding", "reason": f"the file is not valid UTF-8; read as {enc['value']} with low confidence", "candidates": []})
    delim, dconf, dask = _sniff(text)
    st["delimiter"] = {"value": delim, "confidence": round(dconf, 3)}
    if dask:
        res["asks"].append({"kind": "delimiter", "reason": "the delimiter is a close call", "candidates": [{"line": 1, "text": raw(1)}]})

    recs, err = _parse(text, delim)
    res["lines_parsed"] = recs[-1][0] if recs else 0
    if not recs:
        _fail(res, f"the file could not be parsed: {err or 'no records'}")
        return
    if err:
        res["asks"].append({"kind": "parse_error", "reason": f"parsing stopped near line {recs[-1][0] + 1}: {err}",
                            "candidates": [{"line": recs[-1][0] + 1, "text": raw(recs[-1][0] + 1)}]})
    nb = [(ln, r) for ln, r in recs if _filled(r)]
    res["blanks"] = [ln for ln, r in recs if not _filled(r)]
    if not nb:
        _fail(res, "the file has no non-empty lines")
        return

    # header ---------------------------------------------------------------
    wmode = Counter(len(r) for _, r in nb[:200]).most_common(1)[0][0]
    sample, cands, dense = nb[:SAMPLE_LINES], [], 0
    for i, (ln, row) in enumerate(sample):
        c = _score(row, [r for _, r in nb[i + 1:i + 1 + BELOW_ROWS]], wmode, dense)
        c.update(index=i, line=ln, key=tuple(x.strip() for x in row))
        dense += c["fill"] >= DENSE_FILL
        cands.append(c)
    plausible = sorted((c for c in cands if c["labelness"] >= PLAUSIBLE_LABELNESS and c["fill"] >= DENSE_FILL),
                       key=lambda c: -c["score"])
    headerless = not plausible
    hidx = None
    if headerless:
        first = next((c for c in cands if c["fill"] >= DENSE_FILL), cands[0])
        res["asks"].append({"kind": "headerless", "reason": "no line looks like a header: the first rows look like data",
                            "candidates": [{"line": first["line"], "text": raw(first["line"]), "score": round(first["score"], 3)}]})
        st["header"] = {"decided": False, "line": None, "generated_names": True}
    else:
        top = plausible[0]
        second = next((c for c in plausible[1:] if c["key"] != top["key"]), None)  # an exact repeat of the top is not a rival
        margin = top["score"] - (second["score"] if second else 0.0)
        hidx = top["index"]
        st["header"] = {"decided": True, "line": top["line"], "score": round(top["score"], 3), "margin": round(margin, 3)}
        if top["score"] < HEADER_MIN_SCORE or margin < HEADER_MIN_MARGIN:
            shown = [top] + ([second] if second else [])
            res["asks"].append({"kind": "header", "reason": "the header line is a close call" if second else "the best header candidate is weak",
                                "candidates": [{"line": c["line"], "text": raw(c["line"]), "score": round(c["score"], 3)} for c in shown]})
            st["header"]["decided"] = False
            adjacent = second and abs(second["index"] - top["index"]) == 1
            if adjacent and top["fill"] >= DENSE_FILL and second["fill"] >= DENSE_FILL and \
                    "" in [c.strip() for c in sample[min(top["index"], second["index"])][1]]:
                res["asks"][-1]["kind"] = "two_level_header_suspected"  # detected and asked; not solved in Stage 0

    # a sparse header followed by a row of text labels over numeric columns is a two-level header:
    # detected and asked about, not solved in Stage 0
    if hidx is not None and st["header"]["decided"] and hidx + 2 < len(nb):
        hrow, row1, rest = nb[hidx][1], nb[hidx + 1][1], [r for _, r in nb[hidx + 2:hidx + 2 + BELOW_ROWS]]
        if _filled(hrow) / max(len(hrow), 1) <= 0.75 and _filled(row1):
            over = 0
            for j, c in enumerate(row1):
                col = [r[j].strip() for r in rest if j < len(r) and r[j].strip()]
                if _cls(c) == "text" and col and Counter(_cls(v) for v in col).most_common(1)[0][0] in ("number", "date"):
                    over += 1
            if over / _filled(row1) >= 0.5:
                st["header"]["decided"] = False
                res["asks"].append({"kind": "two_level_header_suspected", "reason": "a sparse header is followed by a row of labels over numeric columns",
                                    "candidates": [{"line": nb[hidx][0], "text": raw(nb[hidx][0])}, {"line": nb[hidx + 1][0], "text": raw(nb[hidx + 1][0])}]})

    # columns, trailing phantom fields ------------------------------------
    if headerless:
        body, hdr = nb, [None] * wmode
        T, w = 0, wmode
        names = [f"col_{j + 1}" for j in range(w)]
        st["header_line"], st["header_fields"] = None, []
    else:
        hline, hdr = nb[hidx]
        body = nb[hidx + 1:]
        T = 0
        while T < TRAILING_MAX and T < len(hdr) and not hdr[len(hdr) - 1 - T].strip():
            T += 1
        probe = body[:200]
        if T and probe and sum(1 for _, r in probe if len(r) >= T and all(not x.strip() for x in r[len(r) - T:])) / len(probe) < TRAILING_AGREEMENT:
            T = 0
        w = len(hdr) - T
        names, seen = [], {}
        for j in range(w):
            base = hdr[j].strip() or f"unnamed_{j + 1}"
            if not hdr[j].strip():
                res["flags"].append({"line": hline, "col_index": j + 1, "reason": "blank_header_cell", "raw": raw(hline)})
            elif j == 0 and _UNNAMED.match(hdr[j].strip()):
                res["flags"].append({"line": hline, "col_index": 1, "reason": "index_column_suspected", "raw": raw(hline)})
            n = seen.get(base.lower(), 0) + 1
            seen[base.lower()] = n
            if n > 1:
                res["flags"].append({"line": hline, "col_index": j + 1, "reason": "duplicate_header_cell", "raw": raw(hline)})
            names.append(base if n == 1 else f"{base}_{n}")
        st["header_line"], st["header_fields"] = hline, list(hdr)
    st["trailing_fields"], st["width"] = T, w

    # rows: strip phantom fields, then totals, footers, repeated headers, ragged --
    rows = []
    for ln, r in body:
        r = list(r)
        for _ in range(T):
            if len(r) > w and not r[-1].strip():
                r.pop()
        rows.append((ln, r))
    fillr = lambda r: _filled(r) / max(w, 1)
    exclude = {}
    for ln, r in rows:
        first = next((c.strip() for c in r[:2] if c.strip()), "")  # the label cell: first non-empty of the first two
        if first and _TOTAL.match(first):
            exclude[ln] = ("total_row", [])
    totals = [ln for ln, (why, _) in exclude.items() if why == "total_row"]
    if totals:  # a total closes the table: the few lines after the last one are footer notes
        after = [(ln, r) for ln, r in rows if ln > max(totals) and ln not in exclude]
        if len(after) <= FOOTER_MIN_LINES:
            for ln, _ in after:
                exclude[ln] = ("footer_note", [])

    def footer_like(r):  # a nearly empty line, or a short line that reads like a sentence ("Generated by X, 2024-03-01")
        first = next((c.strip() for c in r if c.strip()), "")
        return fillr(r) < FOOTER_FILL or (len(r) < w and len(first.split()) >= 2 and _cls(first) == "text")

    tail = 0
    for ln, r in reversed(rows):
        if ln in exclude or footer_like(r):
            tail += 1
        else:
            break
    if tail and tail <= max(FOOTER_MIN_LINES, int(FOOTER_MAX_SHARE * len(rows))):
        for ln, r in rows[len(rows) - tail:]:
            exclude.setdefault(ln, ("footer_note", []))
    if not headerless:
        hnorm = [h.strip() for h in hdr[:w]]
        for ln, r in rows:
            if ln not in exclude and [x.strip() for x in r[:w]] == hnorm:
                exclude[ln] = ("repeated_header", [])
    remaining = [(ln, r) for ln, r in rows if ln not in exclude]
    wellformed = [r for _, r in remaining if len(r) == w]
    prof = {}
    for j in range(w):
        col = [_cls(r[j]) for r in wellformed if r[j].strip()]
        if col:
            top, n = Counter(col).most_common(1)[0]
            prof[j] = top if n / len(col) >= 0.8 else "mixed"
    text_cols = [j for j, k in prof.items() if k == "text"]
    ragged = [(ln, r) for ln, r in remaining if len(r) != w and not (len(r) > w and not any(x.strip() for x in r[w:]))]
    kept = []
    if remaining and len(ragged) / len(remaining) > RAGGED_BREAKER:
        res["asks"].append({"kind": "ragged_breaker", "reason": f"{len(ragged)} of {len(remaining)} rows have the wrong field count: "
                            "the delimiter, quoting or encoding is more likely wrong than the rows",
                            "candidates": [{"line": ln, "text": raw(ln)} for ln, _ in ragged[:3]]})
        ragged = []
        kept = [(ln, (r + [""] * w)[:w]) for ln, r in remaining]
    else:
        bad = {ln for ln, _ in ragged}
        for ln, r in remaining:
            if ln not in bad:
                kept.append((ln, (r + [""] * w)[:w]))
                continue
            if len(r) > w:
                tags = ["extra_field_unquoted_delimiter_suspected"] if len(text_cols) == 1 else []
                exclude[ln] = ("extra_field", tags)
            elif all(not c.strip() or prof.get(j) in (None, "text", "mixed") or _cls(c) == prof[j] for j, c in enumerate(r)):
                kept.append((ln, (r + [""] * w)[:w]))
                res["flags"].append({"line": ln, "reason": "possible_shift", "raw": raw(ln)})
            else:
                exclude[ln] = ("possible_shift", [])
    for ln, (reason, tags) in sorted(exclude.items()):
        res["excluded"].append({"line": ln, "reason": reason, "raw": raw(ln), "tags": tags})
    res["rows"] = kept
    res["columns"] = [{"name": n, "position": j + 1} for j, n in enumerate(names)]
    st["data_start_line"] = kept[0][0] if kept else None
    st["data_end_line"] = kept[-1][0] if kept else None

    # identifier columns: digit strings of one fixed width, some with a leading zero ------
    for j in range(w):
        vals = [r[j].strip() for _, r in kept if r[j].strip()]
        digits = [v for v in vals if v.isdigit()]
        if len(vals) >= 5 and len(digits) / len(vals) >= ID_SHARE:
            (width, n), = Counter(len(v) for v in digits).most_common(1)
            if width >= 3 and n / len(digits) >= ID_SHARE and any(v.startswith("0") and len(v) == width for v in digits):
                res["hints"]["identifier_columns"].append(names[j])


def report(res: dict) -> str:
    st, L = res["structure"], []
    L.append(f"status: {res['status']}" + (f" — {res['reason']}" if res["reason"] else "") + f"  (lines parsed: {res['lines_parsed']})")
    if st:
        e, d, h = st["encoding"], st["delimiter"], st.get("header", {})
        L.append(f"encoding: {e['value']}{' +BOM' if e['bom'] else ''} (confidence {e['confidence']})   delimiter: {d['value']!r} (confidence {d['confidence']})")
        L.append(f"header: line {h.get('line')} " + ("decided" if h.get("decided") else "NOT decided") +
                 (f" (score {h['score']}, margin {h['margin']})" if "score" in h else "") +
                 f"   columns: {st.get('width')}   phantom trailing fields: {st.get('trailing_fields')}")
        L.append(f"data rows: {len(res['rows'])}  (lines {st.get('data_start_line')}-{st.get('data_end_line')})   blank lines skipped: {len(res['blanks'])}")
    for x in res["excluded"][:8]:
        L.append(f"  excluded line {x['line']}: {x['reason']} {x['tags'] or ''} | {x['raw'][:70]}")
    for x in res["flags"][:8]:
        L.append(f"  flagged  line {x['line']}: {x['reason']} | {x['raw'][:70]}")
    for a in res["asks"]:
        L.append(f"  ASK [{a['kind']}]: {a['reason']}")
        for c in a["candidates"]:
            L.append(f"       line {c['line']}: {c['text'][:90]}")
    if res["hints"]["identifier_columns"]:
        L.append(f"identifier columns kept as text: {res['hints']['identifier_columns']}")
    return "\n".join(L)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python clean_read.py FILE")
    with open(sys.argv[1], "rb") as f:
        print(report(read(f.read())))
